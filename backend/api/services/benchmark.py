"""Benchmark orchestration service.

Evaluates a router by routing each query in its test set and looking up that
routed model's ALREADY-MEASURED performance/latency/token-usage for that
exact query from routing_data_test (generated by the existing
llmrouter/data pipeline) -- this is "offline" scoring: it reuses real,
previously-computed evaluation results rather than requiring a live API call
per query, matching this phase's requirement to build this as an
orchestration layer over existing evaluation data/logic, not a reimplementation.
"""

from collections import Counter
from typing import Dict, List, Optional

from backend.api.schemas.benchmark import BenchmarkResult
from backend.api.services.config_resolver import resolve_config


def _load_router_for_benchmark(router_name: str, config_path: str):
    from llmrouter.cli.router_inference import load_router

    return load_router(router_name, resolve_config(config_path))


def run_benchmark(
    router_name: str, config_path: str, dataset: str = "default", sample_size: Optional[int] = None
) -> BenchmarkResult:
    router_instance = _load_router_for_benchmark(router_name, config_path)

    test_df = getattr(router_instance, "routing_data_test", None)
    if test_df is None or len(test_df) == 0:
        raise ValueError(
            f"Router '{router_name}' has no routing_data_test loaded -- check its "
            f"config's data_path.routing_data_test."
        )

    if dataset != "default" and "task_name" in test_df.columns:
        test_df = test_df[test_df["task_name"] == dataset]

    queries = test_df["query"].unique().tolist()
    if sample_size:
        queries = queries[:sample_size]

    routing_counts: Counter = Counter()
    performances: List[float] = []
    latencies: List[float] = []
    token_counts: List[float] = []
    failures = 0

    for query in queries:
        try:
            result = router_instance.route_single({"query": query})
            model_name = result.get("model_name") or result.get("predicted_llm")
            routing_counts[model_name] += 1

            row = test_df[(test_df["query"] == query) & (test_df["model_name"] == model_name)]
            if len(row) == 0:
                failures += 1
                continue
            performances.append(float(row.iloc[0]["performance"]))
            if "response_time" in row.columns:
                latencies.append(float(row.iloc[0]["response_time"]))
            if "token_num" in row.columns:
                token_counts.append(float(row.iloc[0]["token_num"]))
        except Exception:
            failures += 1

    accuracy = sum(performances) / len(performances) if performances else 0.0
    avg_latency = sum(latencies) / len(latencies) if latencies else 0.0
    avg_tokens = sum(token_counts) / len(token_counts) if token_counts else 0.0

    return BenchmarkResult(
        router=router_name,
        dataset=dataset,
        num_queries=len(queries),
        accuracy=accuracy,
        average_latency_seconds=avg_latency,
        average_token_usage=avg_tokens,
        routing_distribution=dict(routing_counts),
        failures=failures,
        evaluation_summary=(
            f"{len(performances)}/{len(queries)} queries scored via existing "
            f"routing_data_test performance values; {failures} failed/unmatched."
        ),
    )


def run_benchmark_compare(
    router_configs: Dict[str, str], dataset: str = "default", sample_size: Optional[int] = None
) -> List[BenchmarkResult]:
    results = [
        run_benchmark(name, config_path, dataset, sample_size)
        for name, config_path in router_configs.items()
    ]
    return sorted(results, key=lambda r: r.accuracy, reverse=True)
